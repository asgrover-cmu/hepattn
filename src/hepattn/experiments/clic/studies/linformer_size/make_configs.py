"""Generate the Linformer-everywhere versions of mmfsz's paper-tag model-size arms.

Arms (mmfsz/hepattn clic-paper-main, studies/model_size), all from the v7-width model:
  small  configs/base.yaml narrowed to dim 64, 8 heads, class head [64, 128, 32], regression head 134 -> [128, 128, 128, 64, 32]
  A2 hidden_dim_scale 2 -> 1 in every encoder and decoder dense, A3 dim 48 / 6 heads / heads x0.75,
  A4 encoder 6 -> 5 layers, A6 decoder 4 -> 3 layers, S1 no reverse cross-attention,
  C1 = A2+A3+A4, C3 = A2+A3, C4 = A3+A4, C5 = A2+A4.
Each gets masked-linformer in every attention with constituents ordered by phi. The plain small model is written too, as the
control that this code line reproduces mmfsz's reference.
Usage: python make_configs.py <configs/base.yaml> <outdir>
"""

import sys
from pathlib import Path

base, outdir = Path(sys.argv[1]).read_text(), Path(sys.argv[2])

ENC_ATTN = (
    "          num_register_tokens: 8\n          attn_kwargs:\n            num_heads: {h}\n          dense_kwargs:\n            activation: SwiGLU\n"
)
DEC_ATTN = (
    "          self_attn_norm_kv: true\n          attn_kwargs:\n            num_heads: {h}\n          dense_kwargs:\n            activation: SwiGLU\n"
)


def sub1(s, old, new):
    assert s.count(old) == 1, (old, s.count(old))
    return s.replace(old, new)


def small(s):
    s = sub1(s, "      dim: &dim 256\n", "      dim: &dim 64\n")
    s = sub1(s, ENC_ATTN.format(h=16), ENC_ATTN.format(h=8))
    s = sub1(s, DEC_ATTN.format(h=16), DEC_ATTN.format(h=8))
    s = sub1(s, "hidden_layers: [256, 128, 32]", "hidden_layers: [64, 128, 32]")
    s = sub1(s, "input_size: 518\n", "input_size: 134\n")  # 2 * dim + 6 raw node variables
    return sub1(s, "hidden_layers: [512, 256, 128, 64, 32]", "hidden_layers: [128, 128, 128, 64, 32]")


def heads(s):
    return "6" if "dim: &dim 48" in s else "8"


def a2(s):
    for block in (ENC_ATTN, DEC_ATTN):
        old = block.format(h=heads(s))
        s = sub1(s, old, old + "            hidden_dim_scale: 1\n")
    return s


def a3(s):
    for block in (ENC_ATTN, DEC_ATTN):
        s = sub1(s, block.format(h=8), block.format(h=6))
    s = sub1(s, "      dim: &dim 64\n", "      dim: &dim 48\n")
    s = sub1(s, "hidden_layers: [64, 128, 32]", "hidden_layers: [48, 96, 24]")
    s = sub1(s, "input_size: 134\n", "input_size: 102\n")
    return sub1(s, "hidden_layers: [128, 128, 128, 64, 32]", "hidden_layers: [96, 96, 96, 48, 24]")


def a4(s):
    return sub1(s, "          num_layers: 6\n", "          num_layers: 5\n")


def a6(s):
    return sub1(s, "        num_decoder_layers: 4\n", "        num_decoder_layers: 3\n")


def s1(s):
    return sub1(s, "          query_update_order: ca_sa_dense\n", "          query_update_order: ca_sa_dense\n          bidirectional_ca: false\n")


def linformer(s):
    h = heads(s)
    enc, dec = f"          attn_kwargs:\n            num_heads: {h}\n", f"          attn_kwargs:\n            num_heads: {h}\n"
    s = sub1(s, "          attn_type: flash-varlen\n", "          attn_type: linformer\n")
    s = sub1(
        s,
        "          num_register_tokens: 8\n" + enc,
        "          num_register_tokens: 8\n" + enc + "            linformer_seq_len: 168\n            linformer_k: 64\n",
    )
    s = sub1(
        s,
        "          self_attn_norm_kv: true\n" + dec,
        "          self_attn_norm_kv: true\n"
        + dec.replace("attn_kwargs:\n", "attn_kwargs:\n            attn_type: linformer\n")
        + "            linformer_seq_len: 160\n            linformer_k: 64\n",
    )
    return sub1(s, "      dim: &dim", "      input_sort_field: phi\n      dim: &dim")


ARMS = {
    "ref": [],
    "A2_mlp1x": [a2],
    "A3_dim48": [a3],
    "A4_enc5": [a4],
    "A6_dec3": [a6],
    "S1_nobidir": [s1],
    "C1_a2a3a4": [a3, a2, a4],
    "C3_a2a3": [a3, a2],
    "C4_a3a4": [a3, a4],
    "C5_a2a4": [a2, a4],
}

outdir.mkdir(parents=True, exist_ok=True)
for arm, fns in ARMS.items():
    s = small(base)
    for fn in fns:
        s = fn(s)
    variants = {f"small_{arm}_linformer": linformer(s)}
    if arm == "ref":
        variants["small_ref"] = s
    for name, text in variants.items():
        (outdir / f"{name}.yaml").write_text("# Generated by make_configs.py; do not edit.\n" + sub1(text, "name: clic_v6\n", f"name: clic_{name}\n"))
        print("wrote", name)
